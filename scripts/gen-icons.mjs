#!/usr/bin/env node
/**
 * Generates src/ui/icons/glyphs.ts from Phosphor (regular + fill) and our custom icons
 * in design/icons/custom (256×256 grid, <path> elements only; `name.svg` + `name-fill.svg`).
 * Only listed icons are bundled, so the app ships a few KB of path data, not 9,000 icons.
 */
import fs from 'node:fs';
import path from 'node:path';
import { optimize } from 'svgo';

const root = path.resolve(import.meta.dirname, '..');
const phosphorDir = path.join(root, 'node_modules/@phosphor-icons/core/assets');
const customDir = path.join(root, 'design/icons/custom');
const out = path.join(root, 'src/ui/icons/glyphs.ts');
const { phosphor } = JSON.parse(fs.readFileSync(path.join(root, 'scripts/icons.json'), 'utf8'));

/** Returns [{d, stroke?}] for every <path> in the file; fails loudly on anything else. */
function readPaths(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const { data } = optimize(raw, {
    multipass: true,
    plugins: [{ name: 'preset-default', params: { overrides: { convertShapeToPath: true } } }],
  });
  const body = data.replace(/^<svg[^>]*>|<\/svg>$/g, '');
  const els = body.match(/<[a-z]+[^>]*\/>/g) ?? [];
  return els.map(el => {
    if (!el.startsWith('<path')) throw new Error(`${file}: only <path> elements are supported, got ${el}`);
    const d = /\sd="([^"]+)"/.exec(el)?.[1];
    if (!d) throw new Error(`${file}: path without d`);
    return /stroke=/.test(el) ? { d, stroke: true } : { d };
  });
}

const glyphs = {};
for (const name of phosphor) {
  glyphs[name] = {
    regular: readPaths(path.join(phosphorDir, 'regular', `${name}.svg`)),
    fill: readPaths(path.join(phosphorDir, 'fill', `${name}-fill.svg`)),
  };
}
if (fs.existsSync(customDir)) {
  for (const f of fs.readdirSync(customDir).filter(f => f.endsWith('.svg') && !f.endsWith('-fill.svg'))) {
    const name = f.replace(/\.svg$/, '');
    const fillFile = path.join(customDir, `${name}-fill.svg`);
    glyphs[name] = {
      regular: readPaths(path.join(customDir, f)),
      fill: readPaths(fs.existsSync(fillFile) ? fillFile : path.join(customDir, f)),
    };
  }
}

const src = `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit. Run \`npm run icons\`.
// Phosphor Icons (MIT) + custom icons from design/icons/custom.
import type { GlyphSet } from './types';

export const glyphs = ${JSON.stringify(glyphs)} as const satisfies Record<string, GlyphSet>;

export type IconName = keyof typeof glyphs;
`;
fs.writeFileSync(out, src);
console.log(`icons: wrote ${Object.keys(glyphs).length} glyph sets → ${path.relative(root, out)} (${(src.length / 1024).toFixed(1)} KB)`);
